// Занятие 2. Основы архитектуры компьютера
//
// Лекция посвящена моделям компьютера, процессору и памяти,
// видам оперативной памяти (стек, куча, статическая память)
// и основам параллельного исполнения.
// Здесь — безопасный Rust-аналог того, что на низком уровне
// происходит с указателями и памятью.

/// Счётчик запусков программы.
/// Статически выделенная память: адрес и размер фиксированы
/// на этапе компиляции, живёт всё время работы программы.
static GREETING: &str = "Привет из статической памяти!";

fn main() {
    println!("{GREETING}");

    // ---- Статическая память ----
    // static доступна всей программе и существует всё время её работы.
    static MAX_DEPTH: usize = 5;
    println!("MAX_DEPTH (static) = {MAX_DEPTH}");

    // ---- Стек ----
    // Локальные переменные размещаются на стеке.
    // Стек работает по принципу LIFO: последним пришёл — первым ушёл.
    let a = 1;
    let b = 2;
    let sum = add_on_stack(a, b);
    println!("add_on_stack({a}, {b}) = {sum}");

    // Стек растёт при вложенных вызовах (рекурсия):
    println!("factorial(5) = {}", factorial(5));

    // ---- Стек как структура данных ----
    // Реализация стека на Vec: push кладёт сверху, pop забирает сверху.
    let mut stack: Vec<i32> = Vec::new();
    for i in 1..=3 {
        stack.push(i);
        println!("push -> стек: {stack:?}");
    }
    while let Some(top) = stack.pop() {
        println!("pop  <- {top}, стек: {stack:?}");
    }

    // ---- Куча ----
    // Box — небольшая отслеживающая структура на стеке, которая
    // владеет аллокацией на куче (выделенной аллокатором).
    let boxed = Box::new(42_i32);
    println!("Box на куче: {boxed}");

    // ---- RAII ----
    // Привязывание ресурса (памяти кучи) к отслеживающей структуре:
    // когда Tracker выходит из области видимости, вызывается Drop
    // и ресурс освобождается — программист делает это вручную.
    {
        let _t = Tracker::new("внутренний блок");
        println!("...конец блока, сейчас сработает Drop");
    }

    // ---- Указатели как адреса ----
    // На низком уровне указатель — это число-адрес в памяти.
    // Адрес переменной на стеке и данных в куче можно посмотреть как число.
    let stack_value = 7;
    let heap_value = Box::new(7);
    println!("адрес переменной на стеке: {:p}", &stack_value);
    println!("адрес данных на куче:      {:p}", heap_value);
}

/// Функция: её аргументы и локальные переменные живут на стеке.
fn add_on_stack(x: i32, y: i32) -> i32 {
    let local = x + y; // промежуточный результат — тоже стек
    local
}

/// Классический пример рекурсии: каждый вызов добавляет кадр на стек.
fn factorial(n: u64) -> u64 {
    if n <= 1 {
        1
    } else {
        n * factorial(n - 1)
    }
}

/// Структура, владеющая ресурсом (RAII): Drop освобождает ресурс.
struct Tracker {
    name: &'static str,
}

impl Tracker {
    fn new(name: &'static str) -> Self {
        println!("Tracker::new({name}) — ресурс выделен");
        Tracker { name }
    }
}

impl Drop for Tracker {
    fn drop(&mut self) {
        println!("Drop({}) — ресурс освобождён", self.name);
    }
}
